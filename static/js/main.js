function applyTranslations(lang, persist = false) {
  const currentLang = translations[lang] ? lang : DEFAULT_LANGUAGE;
  document.documentElement.lang = currentLang;

  const brandEl = document.querySelector('.brand');
  if (brandEl && !brandEl.dataset.i18n) {
    brandEl.dataset.i18n = 'nav.brand';
  }

  // Ensure about.text3 and about.text4 paragraphs exist even if the Go server wasn't restarted
  const aboutText2El = document.querySelector('[data-i18n="about.text2"]');
  if (aboutText2El && aboutText2El.parentElement) {
    const aboutCard = aboutText2El.parentElement;
    ['about.text3', 'about.text4'].forEach((key) => {
      if (!aboutCard.querySelector(`[data-i18n="${key}"]`)) {
        const p = document.createElement('p');
        p.dataset.i18n = key;
        aboutCard.appendChild(p);
      }
    });
  }

  renderTechSection(currentLang);
  renderExperienceSection(currentLang);
  renderPortfolioSection(currentLang);

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    const translation = translations[currentLang][key];
    if (translation) {
      if (key === 'about.text1') {
        element.innerHTML = translation;
      } else {
        element.textContent = translation;
      }
    }
  });

  if (translations[currentLang]['hero.name']) {
    document.title = `${translations[currentLang]['hero.name']} | ${translations[currentLang]['hero.role'] || 'Developer'}`;
  }

  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    const translation = translations[currentLang][key];
    if (translation) element.placeholder = translation;
  });

  const select = document.getElementById('languageSelect');
  if (select) select.value = currentLang;

  const currentCodeEl = document.getElementById('langCurrentCode');
  if (currentCodeEl) {
    currentCodeEl.textContent = languageCodeMap[currentLang] || currentLang.toUpperCase();
  }

  document.querySelectorAll('.lang-option').forEach((option) => {
    const isActive = option.dataset.lang === currentLang;
    option.classList.toggle('active', isActive);
    option.setAttribute('aria-selected', isActive ? 'true' : 'false');
  });

  if (persist) {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, currentLang);
  }
}

